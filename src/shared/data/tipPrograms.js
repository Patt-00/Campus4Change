export function filterTipProgramGroups(query = '') {
  const normalized = query.trim().toLowerCase();
  if (!normalized) {
    return tipProgramGroups;
  }
  return tipProgramGroups
    .map(campus => ({
      ...campus,
      colleges: campus.colleges
        .map(collegeGroup => ({
          ...collegeGroup,
          programs: collegeGroup.programs.filter(item =>
            [campus.campus, collegeGroup.name, item.name]
              .join(' ')
              .toLowerCase()
              .includes(normalized),
          ),
        }))
        .filter(collegeGroup => collegeGroup.programs.length),
    }))
    .filter(campus => campus.colleges.length);
}
